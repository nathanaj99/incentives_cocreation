"""
drafts_cleaned.csv: the first three full drafts in each AI participant's
chat, extracted verbatim from the AI's replies by an LLM (OpenAI; needs
OPENAI_API_KEY).

  first_draft   first complete draft substantially GENERATED by the AI
                (a light edit of a participant-written draft does not count)
  second_draft, third_draft
                the next complete versions returned by the AI, however much
                the participant contributed

If there is no qualifying first draft, all three are blank. Each extracted
draft is checked to be a verbatim substring of a later reply than the
previous draft; failures are retried with feedback.

Progress is checkpointed per participant in drafts_cleaned.checkpoint.json
(keyed to the input file, prompt, and model). drafts_cleaned.csv is written
only once every participant has completed; rerun to retry failures.

Input:  processed/ai_requests_explode.csv, raw/submissions.csv (group_key)
Output: processed/drafts_cleaned.csv
"""

import hashlib
import json
import time
from typing import Optional

import pandas as pd
from tqdm.auto import tqdm

from common import (OPENAI_MODEL, atomic_write_json, load_submissions, openai_client, output,
                    parse_args, save_csv, should_skip)
from prompts import drafts_system_prompt

MAX_RETRIES = 3
DRAFT_COLUMNS = ["first_draft", "second_draft", "third_draft"]


def schemas():
    from pydantic import BaseModel, ConfigDict, Field

    class Draft(BaseModel):
        model_config = ConfigDict(extra="forbid")
        source_row: int = Field(description="1-based interaction number for this participant")
        text: str = Field(description="Verbatim contiguous substring from ai_outputs")

    class ParticipantDrafts(BaseModel):
        model_config = ConfigDict(extra="forbid")
        first_draft_decision: str  # audit note only; not written to the CSV
        first_draft: Optional[Draft]
        second_draft: Optional[Draft]
        third_draft: Optional[Draft]

    return ParticipantDrafts


def validate_extraction(result, interactions):
    """Check provenance and ordering (classification itself is the model's job)."""
    previous_row = 0
    missing_seen = False
    for name in DRAFT_COLUMNS:
        draft = getattr(result, name)
        if draft is None:
            missing_seen = True
            continue
        if missing_seen:
            raise ValueError(f"{name} is populated after a missing earlier draft")
        if not previous_row < draft.source_row <= len(interactions):
            raise ValueError(f"{name} has an invalid or non-increasing source_row")
        original = interactions[draft.source_row - 1]["ai_outputs"]
        if not draft.text.strip() or draft.text not in original:
            raise ValueError(f"{name} is not a nonempty verbatim source substring")
        previous_row = draft.source_row


def extract_drafts(client, system_prompt, interactions):
    """Returns (ParticipantDrafts, None) on success or (None, error message)."""
    ParticipantDrafts = schemas()
    user_prompt = (
        "Extract drafts from this one participant's chronological history. "
        "Apply the stricter authorship rule ONLY to first_draft.\n\n"
        + json.dumps(interactions, ensure_ascii=False)
    )
    feedback, last_error = "", ""
    for attempt in range(MAX_RETRIES):
        try:
            response = client.responses.parse(
                model=OPENAI_MODEL,
                input=[
                    {"role": "system", "content": system_prompt},
                    {"role": "user", "content": user_prompt + feedback},
                ],
                text_format=ParticipantDrafts,
            )
            result = response.output_parsed
            if response.status != "completed" or result is None:
                raise ValueError("Response incomplete, refused, or missing parsed output")
            validate_extraction(result, interactions)
            return result, None
        except Exception as error:
            last_error = f"{type(error).__name__}: {error}"
            tqdm.write(f"Attempt {attempt + 1}/{MAX_RETRIES}: {last_error}")
            if isinstance(error, ValueError):
                feedback = ("\n\nA previous attempt failed validation: " + str(error)
                            + ". Recheck the source rows and copy the draft verbatim.")
            if attempt < MAX_RETRIES - 1:
                time.sleep(2 ** attempt)
    return None, last_error


def drafts_frame(participant_ids, records):
    """One row per participant (input order); blank cells for missing drafts."""
    rows = []
    for pid in participant_ids:
        result = records[pid]["result"]
        rows.append({"participant_id": pid,
                     **{name: result[name]["text"] if result[name] else "" for name in DRAFT_COLUMNS}})
    df = pd.DataFrame(rows, columns=["participant_id", *DRAFT_COLUMNS])
    # No gaps: a later draft never exists without the earlier ones
    assert not ((df.first_draft == "") & ((df.second_draft != "") | (df.third_draft != ""))).any()
    assert not ((df.second_draft == "") & (df.third_draft != "")).any()
    return df


def run_study(study):
    input_file = output(study, "ai_requests_explode.csv")
    checkpoint = output(study, "drafts_cleaned.checkpoint.json")
    system_prompt = drafts_system_prompt(study)

    # Rows must stay in chronological order within each participant
    df = pd.read_csv(input_file, dtype=str, keep_default_na=False)
    if df["participant_id"].str.strip().eq("").any():
        raise ValueError("Input contains blank participant identifiers")
    participant_ids = df["participant_id"].drop_duplicates().tolist()

    signature = hashlib.sha256(input_file.read_bytes() + b"\0" + system_prompt.encode()
                               + b"\0" + OPENAI_MODEL.encode() + b"\0schema-v1").hexdigest()
    if checkpoint.exists():
        state = json.loads(checkpoint.read_text(encoding="utf-8"))
        if state.get("signature") != signature:
            raise ValueError(f"Input, prompt, model, or schema changed; delete {checkpoint} to start over.")
    else:
        state = {"signature": signature, "model": OPENAI_MODEL, "records": {}}
    records = state["records"]

    done = {pid for pid, r in records.items() if r.get("status") == "completed"}
    print(f"  {len(done)}/{len(participant_ids)} participants already completed")

    client = None  # only created if an API call is needed
    for pid, group in tqdm(df.groupby("participant_id", sort=False), total=len(participant_ids),
                           desc="Extracting drafts"):
        if pid in done:
            continue
        interactions = [
            {"source_row": k, "ai_requests": req, "ai_outputs": out}
            for k, (req, out) in enumerate(group[["ai_requests", "ai_outputs"]].itertuples(index=False), start=1)
        ]
        if not any(item["ai_outputs"].strip() for item in interactions):
            result, error = {"first_draft_decision": "No nonempty AI outputs exist.",
                             **{name: None for name in DRAFT_COLUMNS}}, None
        else:
            client = client or openai_client()
            parsed, error = extract_drafts(client, system_prompt, interactions)
            result = parsed.model_dump() if parsed is not None else None

        if result is not None:
            records[pid] = {"status": "completed", "result": result}
            done.add(pid)
        else:
            # Failures are retried next run (they are NOT "no draft" results)
            records[pid] = {"status": "failed", "error": error}
        atomic_write_json(state, checkpoint)

    unfinished = [pid for pid in participant_ids if pid not in done]
    if unfinished:
        print(f"  {len(unfinished)} participants failed; see {checkpoint.name} and rerun.")
        return None

    drafts = drafts_frame(participant_ids, records)
    submissions = load_submissions(study)
    drafts = drafts.merge(submissions[["participant_id", "group_key"]], on="participant_id", how="left")
    print("  Nonblank drafts:", {n: int(drafts[n].ne("").sum()) for n in DRAFT_COLUMNS})
    return drafts


def main():
    args = parse_args(__doc__)
    for study in args.study:
        print(f"Study {study}")
        out = output(study, "drafts_cleaned.csv")
        if should_skip(out, args.force):
            continue
        drafts = run_study(study)
        if drafts is not None:
            save_csv(drafts, out)


if __name__ == "__main__":
    main()
